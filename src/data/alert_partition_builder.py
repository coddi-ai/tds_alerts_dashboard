"""Write half of the partitioned alert storage (see `src.data.alert_partitions`).

`build_client` reads ``consolidated_alerts.csv`` — exactly as the dashboard used to, through
`fast_io.read_csv` — and regenerates ``{week}/file.parquet`` plus ``_alert_index.parquet``
for the client. It is deterministic and idempotent: a partition whose newly generated bytes equal
the file on disk is left untouched (same mtime, nothing to upload), one that differs is replaced
atomically, and a partition the source no longer produces is removed. The current, in-progress
week is just another week: it is regenerated on every run, so it is never stale.

The source CSV is only ever read.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

from src.data import alert_partitions as layout
from src.data.fast_io import read_csv
from src.utils.date_utils import to_utc_naive

logger = logging.getLogger(__name__)

_TMP_MARKER = ".tmp-"
_LOCK_FILE = ".alerts_partition.lock"
_LOCK_STALE_SECONDS = 2 * 60 * 60
_STRAY_TMP_SECONDS = 24 * 60 * 60
_REPLACE_RETRIES = 6


class PartitionBuildError(RuntimeError):
    pass


@dataclass(frozen=True)
class LocalFile:
    """A file the build produced (or confirmed unchanged), as the S3 sync needs to see it."""

    rel: str
    path: Path
    size: int
    sha256: str
    md5: str
    rows: int


@dataclass
class BuildResult:
    client: str
    source_rows: int = 0
    files: dict[str, LocalFile] = field(default_factory=dict)  # partitions + the index
    written: list[str] = field(default_factory=list)
    unchanged: int = 0
    removed: list[str] = field(default_factory=list)

    @property
    def partition_files(self) -> dict[str, LocalFile]:
        return {rel: item for rel, item in self.files.items() if rel != layout.INDEX_FILE}

    @property
    def partition_rows(self) -> int:
        return sum(item.rows for item in self.partition_files.values())


