# Filesystem helpers
# ---------------------------------------------------------------------------

def _replace(tmp: Path, final: Path) -> None:
    """``os.replace`` with a short retry: on Windows a reader holding the file open can make
    the first attempts fail with a sharing violation."""
    for attempt in range(_REPLACE_RETRIES):
        try:
            os.replace(tmp, final)
            return
        except PermissionError:
            if attempt == _REPLACE_RETRIES - 1:
                raise
            time.sleep(0.05 * (2 ** attempt))


def _digests(path: Path) -> tuple[str, str]:
    sha, md5 = hashlib.sha256(), hashlib.md5(usedforsecurity=False)
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            sha.update(chunk)
            md5.update(chunk)
    return sha.hexdigest(), md5.hexdigest()


def _write_atomic(table: pa.Table, final: Path) -> tuple[bool, str, str, int]:
    """Write ``table`` to ``final`` unless the file already holds exactly these bytes.

    Returns ``(changed, sha256, md5, size)``. Readers never see a half-written file: the bytes
    go to a temp file in the same folder and replace the old file in one step.
    """
    final.parent.mkdir(parents=True, exist_ok=True)
    tmp = final.with_name(f"{final.name}{_TMP_MARKER}{os.getpid()}")
    try:
        pq.write_table(table, tmp, compression="zstd", compression_level=3)
        sha, md5 = _digests(tmp)
        size = tmp.stat().st_size
        if final.is_file() and _digests(final)[0] == sha:
            return False, sha, md5, size
        _replace(tmp, final)
        return True, sha, md5, size
    finally:
        tmp.unlink(missing_ok=True)


class _ClientLock:
    """One build per client at a time (a scheduled run overlapping a manual one)."""

    def __init__(self, directory: Path):
        self.path = directory / _LOCK_FILE
        self._held = False

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        for _ in range(2):
            try:
                fd = os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
            except FileExistsError:
                try:
                    age = time.time() - self.path.stat().st_mtime
                except OSError:
                    continue
                if age < _LOCK_STALE_SECONDS:
                    raise PartitionBuildError(
                        f"Another partition run holds {self.path} (started {int(age)}s ago)"
                    ) from None
                logger.warning("Removing stale partition lock %s (%ds old)", self.path, int(age))
                self.path.unlink(missing_ok=True)
                continue
            with os.fdopen(fd, "w") as handle:
                handle.write(str(os.getpid()))
            self._held = True
            return self
        raise PartitionBuildError(f"Could not take the partition lock {self.path}")

    def __exit__(self, *exc):
        if self._held:
            self.path.unlink(missing_ok=True)


