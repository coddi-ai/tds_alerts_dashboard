def _index_frame(frame: pd.DataFrame, weeks: pd.Series) -> pd.DataFrame:
    def column(name: str):
        return frame[name] if name in frame.columns else pd.Series([None] * len(frame), dtype="object")

    return pd.DataFrame({
        "FusionID": column("FusionID"),
        "UnitId": column("UnitId"),
        "sistema": column("sistema"),
        "Trigger_Var": column("Trigger_Var"),
        "week": weeks.to_numpy(),
        "row_id": range(len(frame)),
    })


def _remove_stale(directory: Path, expected: set[str]) -> list[str]:
    """Delete partitions the source no longer yields, leftover temp files and emptied folders.

    Also clears the previous ``{week}/{unit}/file.parquet`` layout, if one is there. Only paths
    inside week-named folders are touched: ``backtest/``, ``state/``, the CSVs and anything else
    in the client folder are left alone.
    """
    removed = []
    now = time.time()
    for week in layout._subdirs(directory):
        if not layout.is_week_name(week):
            continue
        week_dir = directory / week
        for entry in list(week_dir.iterdir()):
            if entry.is_dir():
                # Previous layout: one folder per unit holding a file.parquet.
                if all(f.name == layout.PARTITION_FILE or _TMP_MARKER in f.name for f in entry.iterdir()):
                    shutil.rmtree(entry, ignore_errors=True)
                    removed.append(f"{week}/{entry.name}/{layout.PARTITION_FILE}")
            elif entry.name == layout.PARTITION_FILE:
                if layout.partition_relpath(week) not in expected:
                    entry.unlink(missing_ok=True)
                    removed.append(layout.partition_relpath(week))
            elif _TMP_MARKER in entry.name:
                try:
                    if now - entry.stat().st_mtime > _STRAY_TMP_SECONDS:
                        entry.unlink(missing_ok=True)
                except OSError:
                    pass
        if not any(week_dir.iterdir()):
            week_dir.rmdir()
    return removed


def build_client(client: str, root: str | os.PathLike | None = None) -> BuildResult:
    """Regenerate every partition (and the index) of one client from its consolidated CSV."""
    directory = layout.client_dir(client, root)
    source = directory / layout.SOURCE_FILE
    if not source.is_file():
        raise PartitionBuildError(f"{source} not found")

    started = time.perf_counter()
    with _ClientLock(directory):
        frame = read_csv(source)
        for required in ("Timestamp", "UnitId"):
            if required not in frame.columns:
                raise PartitionBuildError(f"{source} has no '{required}' column")

        # The same normalization point the dashboard uses, so the week of an alert is the
        # week of the instant every chart and filter sees.
        timestamps = to_utc_naive(frame["Timestamp"])
        weeks = layout.week_starts(timestamps)

        result = BuildResult(client=(client or "").lower(), source_rows=len(frame))
        base = pa.Table.from_pandas(frame, preserve_index=False)
        # `indices` maps each week to the source row positions, ascending.
        groups = frame.groupby(weeks, sort=True).indices if len(frame) else {}
        for week, positions in groups.items():
            table = base.take(pa.array(positions, pa.int64()))
            metadata = dict(table.schema.metadata or {})
            metadata[layout.ROW_IDS_KEY] = json.dumps([int(p) for p in positions]).encode()
            table = table.replace_schema_metadata(metadata)
            rel = layout.partition_relpath(week)
            path = directory / week / layout.PARTITION_FILE
            changed, sha, md5, size = _write_atomic(table, path)
            result.files[rel] = LocalFile(rel, path, size, sha, md5, len(positions))
            if changed:
                result.written.append(rel)
            else:
                result.unchanged += 1

        index = pa.Table.from_pandas(_index_frame(frame, weeks), preserve_index=False)
        index_final = layout.index_path(directory)
        changed, sha, md5, size = _write_atomic(index, index_final)
        result.files[layout.INDEX_FILE] = LocalFile(
            layout.INDEX_FILE, index_final, size, sha, md5, len(frame)
        )
        if changed:
            result.written.append(layout.INDEX_FILE)

        # Removal runs last: until the new files are in place the old ones keep serving.
        result.removed = _remove_stale(directory, set(result.partition_files))

        if result.partition_rows != result.source_rows:
            raise PartitionBuildError(
                f"{client}: partitions hold {result.partition_rows} rows, "
                f"the source has {result.source_rows}"
            )
    logger.info(
        "%s: %d rows -> %d partitions (%d written, %d unchanged, %d removed) in %.1fs",
        result.client, result.source_rows, len(result.partition_files),
        len([w for w in result.written if w != layout.INDEX_FILE]), result.unchanged,
        len(result.removed), time.perf_counter() - started,
    )
    return result


def discover_clients(root: str | os.PathLike | None = None) -> list[str]:
    """Every client folder under ``data/alerts/golden/`` that has a consolidated CSV."""
    golden = layout.data_root(root) / "alerts" / "golden"
    try:
        names = sorted(entry.name for entry in os.scandir(golden) if entry.is_dir())
    except OSError:
        return []
    return [name for name in names if (golden / name / layout.SOURCE_FILE).is_file()]


