@dataclass
class ValidationReport:
    client: str
    source_rows: int
    partition_rows: int
    partitions: int
    problems: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems


def validate_client(client: str, root: str | os.PathLike | None = None) -> ValidationReport:
    """Check the partitions against the CSV: row totals, columns, dtypes, values and placement.

    Reads the CSV the way the build does and compares it, value for value, with the partitions
    concatenated in source order; every partition's rows must also belong to the week
    its path names.
    """
    directory = layout.client_dir(client, root)
    source = read_csv(directory / layout.SOURCE_FILE)
    weeks = layout.list_weeks(directory)
    paths = layout.partition_paths(directory, weeks)
    problems: list[str] = []

    footer_rows = sum(pq.read_metadata(path).num_rows for path in paths)
    report = ValidationReport(
        client=(client or "").lower(), source_rows=len(source),
        partition_rows=footer_rows, partitions=len(paths), problems=problems,
    )
    if footer_rows != len(source):
        problems.append(f"row count: partitions {footer_rows} != source {len(source)}")

    combined = layout.read_paths(paths)
    if combined.empty and not source.empty:
        problems.append("partitions are empty but the source is not")
        return report
    if list(combined.columns) != list(source.columns):
        problems.append(f"columns differ: {list(combined.columns)} != {list(source.columns)}")
    else:
        for name in source.columns:
            if str(combined[name].dtype) != str(source[name].dtype):
                problems.append(f"dtype of {name}: {combined[name].dtype} != {source[name].dtype}")
        try:
            pd.testing.assert_frame_equal(combined, source, check_dtype=False)
        except AssertionError as exc:
            problems.append(f"values differ from the CSV: {str(exc).splitlines()[0]}")

    for path in paths:
        week = path.parent.name
        part = layout.read_paths([path], columns=["Timestamp"])
        if part.empty:
            problems.append(f"{week} is empty")
            continue
        found = set(layout.week_starts(to_utc_naive(part["Timestamp"])))
        if found != {week}:
            problems.append(f"{week} holds rows of {sorted(found)}")
    return report
