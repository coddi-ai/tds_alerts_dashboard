# Build
# ---------------------------------------------------------------------------

def _index_frame(frame: pd.DataFrame, weeks: pd.Series, part_sha: dict[str, str]) -> pd.DataFrame:
    columns = [name for name in _GROUP_COLUMNS if name in frame.columns]
    keyed = frame[columns].copy()
    keyed["week"] = weeks.to_numpy()
    keyed["__row"] = np.arange(len(frame))
    grouped = keyed.groupby(columns, sort=False, dropna=False).agg(
        week=("week", "first"), rows=("__row", "size"), first_row=("__row", "min"),
    ).reset_index()
    grouped["rows"] = grouped["rows"].astype("int64")
    grouped["part_sha"] = grouped["week"].map(part_sha)
    return grouped


def _remove_stale(directory: Path, expected: set[str]) -> list[str]:
    """Delete telemetry partitions the source no longer yields, and emptied folders.

    Only ``telemetry.parquet`` files (and their stray temp files) inside week-named folders are
    touched: the alerts partitions, ``backtest/``, ``state/``, the CSVs and anything else in the
    client folder are left alone.
    """
    removed = []
    now = time.time()
    for week in alerts_layout._subdirs(directory):
        if not layout.is_telemetry_week(week):
            continue
        week_dir = directory / week
        target = layout.partition_path(directory, week)
        if target.is_file() and layout.partition_relpath(week) not in expected:
            target.unlink(missing_ok=True)
            removed.append(layout.partition_relpath(week))
        for entry in list(week_dir.glob(f"{layout.TELEMETRY_FILE}{_TMP_MARKER}*")):
            try:
                if now - entry.stat().st_mtime > _STRAY_TMP_SECONDS:
                    entry.unlink(missing_ok=True)
            except OSError:
                pass
        if not any(week_dir.iterdir()):
            week_dir.rmdir()
    return removed


def build_client(
    client: str, source_file: str, root: str | os.PathLike | None = None
) -> TelemetryBuildResult:
    """Regenerate every telemetry partition (and the index) of one client from its CSV."""
    directory = layout.client_dir(client, root)
    source = source_path(client, source_file, root)
    if not source.is_file():
        raise TelemetrySourceMissing(f"{source} not found")

    started = time.perf_counter()
    with _ClientLock(directory):
        frame = read_source(source)
        for required in ("AlertID", "Unit"):
            if required not in frame.columns:
                raise PartitionBuildError(f"{source} has no '{required}' column")
        weeks, stats = assign_weeks(frame, _alert_frame(directory))

        result = TelemetryBuildResult(client=(client or "").lower(), source_rows=len(frame), **stats)
        base = pa.Table.from_pandas(frame, preserve_index=False)
        part_sha: dict[str, str] = {}
        # `indices` maps each week to the source row positions, ascending.
        groups = frame.groupby(weeks, sort=True).indices if len(frame) else {}
        for week, positions in groups.items():
            table = base.take(pa.array(positions, pa.int64()))
            metadata = dict(table.schema.metadata or {})
            metadata[layout.ROW_IDS_KEY] = json.dumps([int(p) for p in positions]).encode()
            table = table.replace_schema_metadata(metadata)
            rel = layout.partition_relpath(week)
            path = layout.partition_path(directory, week)
            changed, sha, md5, size = _write_atomic(table, path)
            part_sha[week] = sha[:16]
            result.files[rel] = LocalFile(rel, path, size, sha, md5, len(positions))
            if changed:
                result.written.append(rel)
            else:
                result.unchanged += 1

        index_frame = _index_frame(frame, weeks, part_sha)
        index_final = layout.index_path(directory)
        changed, sha, md5, size = _write_atomic(
            pa.Table.from_pandas(index_frame, preserve_index=False), index_final
        )
        result.files[layout.INDEX_FILE] = LocalFile(layout.INDEX_FILE, index_final, size, sha, md5, len(index_frame))
        if changed:
            result.written.append(layout.INDEX_FILE)

        # Removal runs last: until the new files are in place the old ones keep serving.
        result.removed = _remove_stale(directory, set(result.partition_files))

        if result.partition_rows != result.source_rows:
            raise PartitionBuildError(
                f"{client}: telemetry partitions hold {result.partition_rows} rows, "
                f"the source has {result.source_rows}"
            )
    result.seconds = time.perf_counter() - started
    logger.info(
        "%s: telemetry %d rows -> %d partitions (%d written, %d unchanged, %d removed) in %.1fs",
        result.client, result.source_rows, len(result.partition_files),
        len([w for w in result.written if w != layout.INDEX_FILE]), result.unchanged,
        len(result.removed), result.seconds,
    )
    if result.unmatched_rows:
        logger.warning(
            "%s: %d telemetry rows (%d distinct AlertID/Unit) match no alert in consolidated_alerts.csv; "
            "kept under %s/ (not dropped). The team must decide how to handle them.",
            result.client, result.unmatched_rows, result.unmatched_keys, layout.UNMATCHED_WEEK,
        )
    if result.ambiguous_keys:
        logger.warning(
            "%s: %d AlertID/Unit pairs are claimed by alerts of different weeks; the first alert's week was used",
            result.client, result.ambiguous_keys,
        )
    return result


# ---------------------------------------------------------------------------
# Local validation (the backfill is checked here before anything goes to S3)
# ---------------------------------------------------------------------------

def validate_client(
    client: str, source_file: str, root: str | os.PathLike | None = None
) -> ValidationReport:
    """Check the partitions against the source CSV: row totals, columns, dtypes, values, placement.

    Reads the CSV the way the build does and compares it, value for value, with the partitions
    concatenated in source order. Then checks that **each row sits in the week of its alert**
    (recomputed from ``consolidated_alerts.csv``, from each partition's recorded source row
    numbers) and that the index agrees with the partitions.
    """
    directory = layout.client_dir(client, root)
    source = read_source(source_path(client, source_file, root))
    weeks_on_disk = layout.list_weeks(directory)
    paths = [layout.partition_path(directory, week) for week in weeks_on_disk]
    problems: list[str] = []

    footer_rows = sum(pq.read_metadata(path).num_rows for path in paths)
    report = ValidationReport(
        client=(client or "").lower(), source_rows=len(source),
        partition_rows=footer_rows, partitions=len(paths), problems=problems,
    )
    if footer_rows != len(source):
        problems.append(f"row count: partitions {footer_rows} != source {len(source)}")

    combined = layout.read_weeks(directory, weeks_on_disk)
    if combined.empty and not source.empty:
        problems.append("telemetry partitions are empty but the source is not")
        return report
    if list(combined.columns) != list(source.columns):
        problems.append(f"columns differ: {list(combined.columns)} != {list(source.columns)}")
    else:
        for name in source.columns:
            if str(combined[name].dtype) != str(source[name].dtype):
                problems.append(f"dtype of {name}: {combined[name].dtype} != {source[name].dtype}")
        try:
            pd.testing.assert_frame_equal(combined, source, check_dtype=False)
        except AssertionError as exc:
            problems.append(f"values differ from the CSV: {str(exc).splitlines()[0]}")

    # Placement: every row in the week of its alert.
    try:
        expected, _ = assign_weeks(source, _alert_frame(directory))
    except PartitionBuildError as exc:
        problems.append(f"cannot check placement: {exc}")
        return report
    seen = np.zeros(len(source), dtype=bool)
    for week, path in zip(weeks_on_disk, paths):
        raw = (pq.read_metadata(path).metadata or {}).get(layout.ROW_IDS_KEY)
        positions = np.array(json.loads(raw) if raw else [], dtype=np.int64)
        if positions.size and (positions.min() < 0 or positions.max() >= len(source)):
            problems.append(f"{week}: recorded source rows are out of range")
            continue
        wrong = expected.to_numpy()[positions] != week
        if wrong.any():
            problems.append(
                f"{week} holds {int(wrong.sum())} rows of other weeks "
                f"(e.g. {sorted(set(expected.to_numpy()[positions][wrong]))[:3]})"
            )
        if seen[positions].any():
            problems.append(f"{week}: rows repeated in another partition")
        seen[positions] = True
    if not seen.all():
        problems.append(f"{int((~seen).sum())} source rows are in no partition")

    # The index agrees with the partitions.
    index = layout.read_index(directory)
    if index.empty and not source.empty:
        problems.append("telemetry index is missing or empty")
    elif not index.empty:
        if int(index["rows"].sum()) != len(source):
            problems.append(f"index rows {int(index['rows'].sum())} != source {len(source)}")
        expected_week = expected.to_numpy()[index["first_row"].to_numpy()]
        if (index["week"].to_numpy() != expected_week).any():
            problems.append("index weeks disagree with the placement of their rows")
        for week in index["week"].unique():
            sha = hashlib.sha256(layout.partition_path(directory, week).read_bytes()).hexdigest()[:16]
            if set(index.loc[index["week"] == week, "part_sha"]) != {sha}:
                problems.append(f"index part_sha of {week} does not match the file")
    return report
